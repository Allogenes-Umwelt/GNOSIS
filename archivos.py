## Toma una carpeta de archivos xml y los guarda en una lista

import os


def archivos(carpeta):
        archivos=[]
        for i in os.scandir(carpeta):
            a=str(i).replace("<DirEntry '"  ,'/')
            b=a.replace("'>",'')
            c=str(carpeta)+b
            archivos.append(c)
            archivos.sort()
        return archivos


